/**
 * Regenerate the query documents the content layer uses.
 *
 * Tina's generated types.ts holds the canonical query strings (including the
 * inlined fragments) but also contains a runtime import of tinacms/dist/client,
 * which cannot be resolved by the Deno server. This script imports the generated
 * module with Node (type stripping) and writes the strings to a small,
 * dependency-free TypeScript module that the site can import.
 *
 * Run after every schema change: node tools/tina/generate-tina-documents.mjs
 */
import { existsSync, symlinkSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const generated = join(root, "tina", "__generated__", "types.ts");

// The generated module imports tinacms/dist/client at runtime. The package is
// installed in tools/tina, so expose it through the project's node_modules just
// for this import, then remove the link so Deno's own resolution is untouched.
const tinacmsLink = join(root, "node_modules", "tinacms");
const createdLink = !existsSync(tinacmsLink);
if (createdLink) {
  symlinkSync("../tools/tina/node_modules/tinacms", tinacmsLink, "dir");
}

let mod;
try {
  mod = await import(pathToFileURL(generated).href);
} finally {
  if (createdLink) unlinkSync(tinacmsLink);
}

const documents = {
  site: mod.SiteDocument,
  home: mod.HomeDocument,
  about: mod.AboutDocument,
  contact: mod.ContactDocument,
  experience: mod.ExperienceDocument,
  projects: mod.ProjectsDocument,
};

const missing = Object.entries(documents)
  .filter(([, value]) => typeof value !== "string")
  .map(([name]) => name);
if (missing.length > 0) {
  throw new Error("Missing generated query documents: " + missing.join(", "));
}

const target = join(root, "lib", "tina", "documents.generated.ts");
const contents = "// Generated by tools/tina/generate-tina-documents.mjs — do not edit.\n" +
  "// Source: tina/__generated__/types.ts (TinaCMS codegen).\n\n" +
  "export const documents = " +
  JSON.stringify(documents, null, 2) +
  " as const;\n";
writeFileSync(target, contents);
console.log("wrote " + target + " (" + Object.keys(documents).length + " documents)");
